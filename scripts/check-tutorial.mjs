import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { restaurantChatDocument } from '../src/restaurant-chat.ts';
import { messages } from '../src/protocol.ts';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1080}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
let calls=0,lastRequest;
await page.route('**/api/generate',async route=>{
  calls++;lastRequest=route.request().postDataJSON();
  if(lastRequest.prompt.includes('failure'))return route.fulfill({status:429,contentType:'application/json',body:JSON.stringify({error:'Test allowance exhausted.'})});
  const patch=calls===1?{cuisine:'italian',party:'4',day:'tomorrow',seating:'patio'}:{party:'6'};
  const doc=restaurantChatDocument({patch},lastRequest.restaurant);
  const wire=messages(doc,lastRequest.surfaceId||crypto.randomUUID()).filter(m=>!(lastRequest.surfaceId&&m.createSurface));
  return route.fulfill({status:200,contentType:'application/x-ndjson',headers:{'x-daily-remaining':'28'},body:wire.map(m=>JSON.stringify(m)).join('\n')});
});
await page.goto('http://127.0.0.1:8793');
await page.getByRole('button',{name:'Send to real AI',exact:true}).click();
await page.getByRole('heading',{name:'Willow & Flour'}).waitFor();
assert.equal(calls,1);
await page.getByRole('button',{name:'Next lesson'}).click();
await page.locator('#choice-select-party').selectOption('2');
assert.equal(calls,1);
assert.equal(await page.locator('#choice-select-seating').inputValue(),'patio');
await page.getByRole('button',{name:'Next lesson'}).click();
await page.locator('#choice-select-party').selectOption('6');
assert.equal(lastRequest.restaurant.party,'2');
assert.equal(lastRequest.restaurant.seating,'patio');
assert.equal(calls,2);
assert.equal(await page.locator('#choice-select-seating').inputValue(),'indoor');
assert.equal(await page.locator('#choice-select-day').inputValue(),'tomorrow');
await page.getByRole('button',{name:'Next lesson'}).click();
await page.getByRole('button',{name:'5:30 PM',exact:true}).click();
await page.getByRole('button',{name:'Confirm demo reservation',exact:true}).click();
await page.getByRole('heading',{name:'Demo reservation confirmed'}).waitFor();
assert.equal(calls,2);
await page.screenshot({path:'artifacts/tutorial-desktop.png',fullPage:true});
await page.getByRole('button',{name:'Live playground',exact:true}).click();
await page.getByLabel('Tell the assistant what changed').fill('failure please');
await page.getByRole('button',{name:'Send dinner request'}).click();
await page.getByText(/Test allowance exhausted/).waitFor();
assert.equal(await page.locator('#choice-select-party').inputValue(),'6');
await page.locator('#choice-select-party').selectOption('4');
assert.equal(await page.locator('#choice-select-party').inputValue(),'4');
await page.setViewportSize({width:390,height:844});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.screenshot({path:'artifacts/tutorial-mobile.png',fullPage:true});
const cspErrors=[];
page.on('console',message=>{if(message.type()==='error'&&message.text().includes('Content Security Policy'))cspErrors.push(message.text());});
await page.route('http://127.0.0.1:8793/sdk-spike/',async route=>{const response=await route.fetch();await route.fulfill({response,headers:{...response.headers(),'content-security-policy':"default-src 'self'; script-src 'self'; style-src 'self' https://fonts.googleapis.com; font-src https://fonts.gstatic.com; connect-src 'self'; img-src 'self' data:; object-src 'none'; base-uri 'self'"}});});
await page.goto('http://127.0.0.1:8793/sdk-spike/');
await page.getByRole('heading',{name:'Your Explorer Active',exact:true}).waitFor();
await page.getByRole('radio',{name:'4WD',exact:true}).check();
await page.getByRole('button',{name:'Review configuration',exact:true}).click();
await page.locator('#sdk-handoff').waitFor();
assert.match(await page.locator('#sdk-event').textContent(),/sdk-review/);
assert.match(await page.locator('#sdk-data').textContent(),/"explorerDrive": "4wd"/);
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.screenshot({path:'artifacts/sdk-spike.png',fullPage:true});
console.log(JSON.stringify({calls,errors,officialSdkBindingAndAction:'passed',mobileOverflow:false}));
await browser.close();
assert.deepEqual(errors,[]);assert.deepEqual(cspErrors,[]);
