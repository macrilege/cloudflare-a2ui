import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1080}});
const errors=[],requests=[],results=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
page.on('request',r=>{if(r.url().endsWith('/api/generate'))requests.push(r.postDataJSON());});
page.on('response',async r=>{if(r.url().endsWith('/api/generate'))results.push({status:r.status(),remaining:r.headers()['x-daily-remaining'],generationMs:r.headers()['x-generation-ms']});});
try{
  await page.goto('https://a2ui-lab.macrilege.workers.dev/');
  await page.getByRole('button',{name:'Send to real AI',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Willow & Flour',exact:true})).toBeVisible({timeout:50000});
  await expect(page.locator('#choice-select-party')).toHaveValue('4');
  await expect(page.locator('#choice-select-seating')).toHaveValue('patio');
  await page.getByRole('button',{name:'Next lesson'}).click();
  await page.locator('#choice-select-party').selectOption('2');
  await page.getByRole('button',{name:'Next lesson'}).click();
  await expect(page.locator('#choice-select-party')).toHaveValue('6',{timeout:50000});
  assert.equal(requests[1].restaurant.party,'2');
  await expect(page.locator('#choice-select-day')).toHaveValue('tomorrow');
  await expect(page.locator('#choice-select-seating')).toHaveValue('indoor');
  await page.getByRole('button',{name:'Next lesson'}).click();
  await page.getByRole('button',{name:'5:30 PM',exact:true}).click();
  await page.getByRole('button',{name:'Confirm demo reservation',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Demo reservation confirmed'})).toBeVisible();
  await page.screenshot({path:'artifacts/live-tutorial-desktop.png',fullPage:true});
  await page.goto('https://a2ui-lab.macrilege.workers.dev/sdk-spike/');
  await page.getByRole('radio',{name:'4WD',exact:true}).check();
  await page.getByRole('button',{name:'Send to real AI',exact:false}).click();
  await expect(page.getByRole('radio',{name:'Vapor Blue Metallic',exact:true})).toBeChecked({timeout:50000});
  await expect(page.getByRole('radio',{name:'4WD',exact:true})).toBeChecked();
  assert.equal(requests[2].draft.explorerDrive,'4wd');
  await page.getByRole('button',{name:'Review configuration',exact:true}).click();
  await expect(page.locator('#sdk-handoff')).toBeVisible();
  assert.match(await page.locator('#sdk-event').textContent(),/sdk-review/);
  await page.screenshot({path:'artifacts/live-sdk-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'artifacts/live-sdk-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:true,results,errors,calls:requests.length,officialFollowUpPreserved4WD:true}));
}finally{await browser.close();}
